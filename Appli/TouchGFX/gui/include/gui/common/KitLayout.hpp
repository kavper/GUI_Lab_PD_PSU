#ifndef KITLAYOUT_HPP
#define KITLAYOUT_HPP
// Designer layout of the kit pages.
//
// Every page has a "Layout" container in TouchGFX Designer that mirrors the
// kit widgets (boxes for cards, text areas for labels, buttons as small
// containers). It is generated from the running UI (simulator export) and is
// what the Designer canvas shows. At runtime the kit widgets are matched to
// it in order; a widget whose position, size, text or typography was edited in
// Designer takes the edited value. Untouched widgets keep their code layout,
// so state dependent layouts (cell count, editors) keep working.
#include <touchgfx/containers/Container.hpp>
#include <touchgfx/Unicode.hpp>
#include <stdint.h>
#include <stdio.h>

namespace kit {
struct LayoutEntry { uint8_t kind, font, visible; int16_t x, y, w, h; uint32_t hash; };
struct LayoutScreen { const LayoutEntry* entries; uint16_t count; };
// Generated by tools/designer_layout.py (KitLayoutTable.cpp), indexed by page.
extern const LayoutScreen layoutScreens[];
extern const unsigned layoutScreenCount;

// Apply Designer edits for a page (called once the page is set up).
// Returns the number of widgets that took a Designer value, -1 if the
// Designer layout does not match this firmware (then nothing is changed).
int applyDesignerLayout(unsigned page, touchgfx::Container& root);
uint32_t textHash(const touchgfx::Unicode::UnicodeChar* text);
#ifdef SIMULATOR
// Simulator export: one JSON object per page with every kit widget.
void exportLayout(FILE* out, unsigned page, const char* name, touchgfx::Container& root, const uint16_t* framebuffer);
#endif
}
#endif
